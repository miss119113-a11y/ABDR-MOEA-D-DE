%{
This model is generated by:
- Loading terrain map
- Creating threats as cylinders
- Creating start and finish points
- Setting ranges and limits
%}

function model=CreateModel(scenarioId)

    if nargin < 1 || isempty(scenarioId)
        scenarioId = localCurrentScenarioId();
    end
    scenarioId = localResolveScenarioId(scenarioId);

    terrainFile = localTerrainFile();
    % Convert the DEM once when the model is created. The frozen evaluator
    % performs thousands of bilinear/continuous-clearance queries per run;
    % repeatedly converting the full integer TIFF inside those queries adds
    % avoidable data-dependent overhead without changing any terrain value.
    H = double(imread(terrainFile)); % Get elevation data
    H (H < 0) = 0;
    MAPSIZE_X = size(H,2); % x index: columns of H
    MAPSIZE_Y = size(H,1); % y index: rows of H
    [X,Y] = meshgrid(1:MAPSIZE_X,1:MAPSIZE_Y); % Create all (x,y) points to plot

    % Map limits
    xmin= 1;
    xmax= MAPSIZE_X;
    
    ymin= 1;
    ymax= MAPSIZE_Y;
    
    zmin = 100;
    zmax = 200;  
 
    spec = localScenarioSpec(scenarioId);

    % Start and end position
    start_location = spec.start;
    end_location = spec.goal;
    
    % Number of path nodes (not including the start position (start node))
    n=10;
    
    % Incorporate map and searching parameters to a model
    model.start=start_location;
    model.end=end_location;
    model.n=n;
    model.xmin=xmin;
    model.xmax=xmax;
    model.zmin=zmin;
    model.ymin=ymin;
    model.ymax=ymax;
    model.zmax=zmax;
    model.MAPSIZE_X = MAPSIZE_X;
    model.MAPSIZE_Y = MAPSIZE_Y;
    model.X = X;
    model.Y = Y;
    model.H = H;
    model.terrainFile = terrainFile;
    model.terrainOverrideActive = isappdata(0,'NAV_TERRAIN_FILE_OVERRIDE');
    model.threats = spec.threats;
    model.scenarioId = scenarioId;
    model.scenarioName = spec.name;
    % Frozen physical-model metadata. Horizontal map coordinates above are
    % DEM grid indices; navigation distances and all reported geometry are
    % expressed in metres through NAV_ConvertPath.
    model.PixelSizeM = 5;
    % Official NMOPSO compares drone_size=1 and danger_dist=10 in the
    % same horizontal grid units as threat radii. Preserve that geometry
    % after converting the 5 m DEM grid to metres.
    model.DroneSizeM = model.PixelSizeM;
    model.SafetyDistM = 10*model.PixelSizeM;
    model.MaxTurnDeg = 45;
    model.MaxClimbDeg = 45;
    model.ObjectiveProtocol = 'NMOPSO_Eqs_3_to_9_physical_units';
    model.ThreatAggregation = 'equal_mean_over_all_threat_segment_pairs';
    model.RepresentativeDecisionRule = 'C=sum(F1:F4)';
    % Dedicated runtime experiments disable model rendering so tic/toc only
    % measures optimization work. Normal experiments keep the original plot.
    disablePlot = false;
    try
        disablePlot = isappdata(0,'NAV_DISABLE_MODEL_PLOT') && ...
            logical(getappdata(0,'NAV_DISABLE_MODEL_PLOT'));
    catch
    end
    if ~disablePlot
        PlotModel(model);
    end
end

function terrainFile = localTerrainFile()
    % Optional benchmark-only hook. Normal/formal runs remain byte-for-byte
    % compatible because the original terrain lookup is used unless a
    % dedicated runner explicitly installs an override.
    terrainFile = '';
    try
        if isappdata(0,'NAV_TERRAIN_FILE_OVERRIDE')
            terrainFile = char(string(getappdata(0,'NAV_TERRAIN_FILE_OVERRIDE')));
        end
    catch
        terrainFile = '';
    end
    if ~isempty(terrainFile)
        if exist(terrainFile,'file') ~= 2
            error('CreateModel:MissingTerrainOverride', ...
                'Terrain override file is missing: %s',terrainFile);
        end
        return;
    end

    terrainFile = which('ChrismasTerrain2.tif');
    if isempty(terrainFile)
        terrainFile = fullfile(lcad_project_root(), 'data', 'terrain', 'ChrismasTerrain2.tif');
    end
end

function scenarioId = localCurrentScenarioId()
    if isappdata(0, 'NAV_SCENARIO_ID')
        scenarioId = getappdata(0, 'NAV_SCENARIO_ID');
    else
        scenarioId = 4;
    end
end

function scenarioId = localResolveScenarioId(scenarioId)
    if ischar(scenarioId)
        token = regexp(scenarioId, '\d+', 'match', 'once');
        if isempty(token)
            error('CreateModel:InvalidScenario', 'Scenario id must be one of 1:4 or 101:112.');
        end
        scenarioId = str2double(token);
    elseif isstring(scenarioId)
        scenarioId = localResolveScenarioId(char(scenarioId));
    else
        scenarioId = double(scenarioId);
    end
    validIds = [1:4 101:112];
    validIds = [validIds localOverrideScenarioIds()];
    if ~isscalar(scenarioId) || ~ismember(scenarioId, validIds)
        error('CreateModel:InvalidScenario', ...
            'Scenario id is not registered by the formal or active supplement protocol.');
    end
end

