end

function ids = localOverrideScenarioIds()
ids = [];
scenarioFile = localScenarioOverrideFile();
if isempty(scenarioFile), return; end
try
    S = load(scenarioFile,'scenarioSpecs');
    if isfield(S,'scenarioSpecs') && isstruct(S.scenarioSpecs)
        ids = double([S.scenarioSpecs.Id]);
    end
catch
    ids = [];
end
end

function spec = localOverrideScenarioSpec(scenarioId)
scenarioFile = localScenarioOverrideFile();
if isempty(scenarioFile)
    error('CreateModel:UnknownScenario', ...
        'Scenario %d is not part of the built-in protocol.',scenarioId);
end
S = load(scenarioFile,'scenarioSpecs');
if ~isfield(S,'scenarioSpecs') || ~isstruct(S.scenarioSpecs)
    error('CreateModel:InvalidScenarioOverride', ...
        'Scenario override file does not contain scenarioSpecs: %s',scenarioFile);
end
idx = find(double([S.scenarioSpecs.Id]) == double(scenarioId),1);
if isempty(idx)
    error('CreateModel:UnknownScenarioOverride', ...
        'Scenario %d is not registered in %s.',scenarioId,scenarioFile);
end
item = S.scenarioSpecs(idx);
required = {'Name','Start','Goal','Threats'};
for k = 1:numel(required)
    if ~isfield(item,required{k})
        error('CreateModel:IncompleteScenarioOverride', ...
            'Scenario %d lacks %s in %s.',scenarioId,required{k},scenarioFile);
    end
end
spec = struct('name',char(string(item.Name)), ...
    'start',double(item.Start(:)), ...
    'goal',double(item.Goal(:)), ...
    'threats',double(item.Threats));
if numel(spec.start) ~= 3 || numel(spec.goal) ~= 3 || ...
        size(spec.threats,2) ~= 4
    error('CreateModel:MalformedScenarioOverride', ...
        'Scenario %d has invalid geometry in %s.',scenarioId,scenarioFile);
end
end

function scenarioFile = localScenarioOverrideFile()
scenarioFile = '';
try
    if isappdata(0,'NAV_SCENARIO_OVERRIDE_FILE')
        scenarioFile = char(string(getappdata(0,'NAV_SCENARIO_OVERRIDE_FILE')));
    end
catch
    scenarioFile = '';
end
if ~isempty(scenarioFile) && exist(scenarioFile,'file') ~= 2
    error('CreateModel:MissingScenarioOverride', ...
        'Scenario override file is missing: %s',scenarioFile);
end
end
